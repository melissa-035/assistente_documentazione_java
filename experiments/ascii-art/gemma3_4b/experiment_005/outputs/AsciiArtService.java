package pl.mgodyn.asciiart.service;

import pl.mgodyn.asciiart.converter.Converter;
import pl.mgodyn.asciiart.io.AsciiArtPrinter;
import java.awt.image.BufferedImage;

/**
 * This class provides a service for converting a BufferedImage to an ASCII art representation.
 * It utilizes a Converter to translate pixel data and an AsciiArtPrinter to format the output.
 */
public class AsciiArtService {

    private final Converter converter;
    private final AsciiArtPrinter printer;

    /**
     * Constructor for the AsciiArtService.
     * Initializes the Converter and AsciiArtPrinter instances.
     */
    public AsciiArtService() {
        this.converter = new Converter();
        this.printer = new AsciiArtPrinter();
    }

    /**
     * Converts a BufferedImage to an ASCII art representation and prints it to the console.
     *
     * @param image The BufferedImage to convert.
     */
    public void convert(BufferedImage image) {
        for (int y = 0; y < image.getHeight(); y++) {
            for (int x = 0; x < image.getWidth(); x++) {
                var pixel = image.getRGB(x, y);
                var ascii = converter.convertPixel2Ascii(pixel);
                printer.add2Row(ascii);
            }
            printer.createNewRow();
        }
    }

    /**
     * Prints the ASCII art representation generated by the service to the console.
     */
    public void print() {
        printer.print();
    }
}
