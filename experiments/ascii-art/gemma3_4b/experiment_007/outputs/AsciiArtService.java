/**
 * Provides a service for converting a BufferedImage to ASCII art.
 * This class handles the conversion process and offers methods to
 * convert the image and print the resulting ASCII art to the console.
 */
public class AsciiArtService {

    private final Converter converter;
    private final AsciiArtPrinter printer;

    /**
     * Creates a new AsciiArtService instance.
     *
     * This constructor initializes the Converter and AsciiArtPrinter
     * objects.
     */
    public AsciiArtService() {
        this.converter = new Converter();
        this.printer = new AsciiArtPrinter();
    }

    /**
     * Converts a BufferedImage to ASCII art and prints it to the console.
     *
     * This method iterates through each pixel of the input image, converts
     * it to an ASCII character using the Converter, and adds the character
     * to the ASCII art row in the printer. A new row is added after each
     * row of ASCII characters is generated.
     *
     * @param image The BufferedImage to convert to ASCII art.
     */
    public void convert(BufferedImage image) {
        for (int y = 0; y < image.getHeight(); y++) {
            for (int x = 0; x < image.getWidth(); x++) {
                var pixel = image.getRGB(x, y);
                var ascii = converter.convertPixel2Ascii(pixel);
                printer.add2Row(ascii);
            }
            printer.createNewRow();
        }
    }

    /**
     * Prints the ASCII art generated by the service to the console.
     * This method utilizes the AsciiArtPrinter to format and output
     * the ASCII art representation of the image.
     */
    public void print() {
        printer.print();
    }
}
